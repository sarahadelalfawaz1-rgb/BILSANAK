# Request Agent: Receives and validates traveler requests

import uuid

class RequestAgent:
    def __init__(self):
        self.name = "Request Agent"
        self.languages = ["English", "Chinese", "French", "Spanish", "Urdu"]
        self.services = [
            "Passport Control",
            "Baggage Services",
            "Check-in and Boarding",
            "Airport Navigation",
            "General Inquiries"
        ]

    def receive_request(self, language, location, service):
        if not all([language, location, service]):
            return {"status": "Invalid", "message": "Missing information"}

        if language not in self.languages:
            return {"status": "Invalid", "message": "Unsupported language"}

        if service not in self.services:
            return {"status": "Invalid", "message": "Unsupported service"}

        request = {
            "request_id": str(uuid.uuid4())[:8],
            "language": language,
            "location": location,
            "service": service,
            "status": "Pending"
        }

        return request

    def send_request(self, request):
        return {
            "performative": "REQUEST",
            "sender": self.name,
            "receiver": "Matching Agent",
            "content": request
        }

# Matching Agent: Finds a suitable available translator

class MatchingAgent:
    def __init__(self):
        self.name = "Matching Agent"

    def find_translator(self, request, translators):
        if request.get("status") != "Pending":
            return None

        for translator in translators:
            if (
                translator["language"] == request["language"]
                and translator["location"] == request["location"]
                and translator["status"] == "Available"
            ):
                return translator

        return None

    def match_request(self, message, translators):
        if message.get("performative") != "REQUEST":
            return {
                "performative": "REFUSE",
                "sender": self.name,
                "receiver": "Request Agent",
                "content": "Invalid message"
            }

        request = message["content"]

        excluded_ids = message.get("excluded_translator_ids", [])
        eligible_translators = [
            translator for translator in translators
            if translator["translator_id"] not in excluded_ids
        ]

        translator = self.find_translator(request, eligible_translators)


        if translator is None:
            return {
                "performative": "INFORM",
                "sender": self.name,
                "receiver": "Request Agent",
                "content": "No available translator"
            }

        return {
            "performative": "REQUEST",
            "sender": self.name,
            "receiver": "Translator Agent",
            "translator_id": translator["translator_id"],
            "content": request
        }

#Translator agent
class TranslatorAgent:
    def __init__(self):
        self.name = "Translator Agent"

    def respond_to_request(self, message, translator, accept):
        request = message["content"]
        translator_id = message["translator_id"]

        if translator["translator_id"] != translator_id:
            raise ValueError("The request was sent to a different translator.")

        if translator["status"] != "Available":
            performative = "REFUSE"
            reason = "Translator is unavailable"
        elif not accept:
            performative = "REFUSE"
            reason = "Translator declined the request"
        else:
            translator["status"] = "Busy"
            performative = "ACCEPT"
            reason = "Translator accepted the request"

        return {
            "performative": performative,
            "sender": self.name,
            "receiver": message["sender"],
            "translator_id": translator_id,
            "content": request.copy(),
            "reason": reason,
        }

#Monitoring agent
class MonitoringAgent:
    def __init__(self):
        self.name = "Monitoring Agent"

    def monitor_service(
        self, translator_reply, *,
        elapsed_minutes, max_wait_minutes,
        arrived, interrupted=False, completed=False
    ):
        if translator_reply["performative"] != "ACCEPT" or completed:
            return None

        if interrupted:
            reason = "Service interrupted"
        elif not arrived and elapsed_minutes >= max_wait_minutes:
            reason = "Translator did not arrive before the waiting limit"
        else:
            return None

        return {
            "performative": "REQUEST",
            "sender": self.name,
            "receiver": "Matching Agent",
            "content": {
                **translator_reply["content"],
                "status": "Pending",
            },
            "excluded_translator_ids": [translator_reply["translator_id"]],
            "reason": reason,
        }

