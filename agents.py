from langsmith import traceable


@traceable(name="Bilisank Request")
def run_request(
    language, location, service, translators, *,
    max_wait_minutes, decisions, service_updates, on_update=None
):
    request_agent = RequestAgent()
    matching_agent = MatchingAgent()
    translator_agent = TranslatorAgent()
    monitoring_agent = MonitoringAgent()

    receive_request = traceable(name="Request Agent - Validate request")(
        request_agent.receive_request
    )
    send_request = traceable(name="Request Agent - Send request")(
        request_agent.send_request
    )
    match_request = traceable(name="Matching Agent - Match translator")(
        matching_agent.match_request
    )
    respond_to_request = traceable(name="Translator Agent - Respond")(
        translator_agent.respond_to_request
    )
    monitor_service = traceable(name="Monitoring Agent - Check service")(
        monitoring_agent.monitor_service
    )


    translators_by_id = {
        translator["translator_id"]: translator
        for translator in translators
    }

    message_log = []
    excluded_ids = []

    def update_status(agent, status):
        if on_update is not None:
            on_update(agent, status)

    update_status("Request Agent", "Validating request")
    request = receive_request(language, location, service)

    if request["status"] == "Invalid":
        update_status("Request Agent", "Invalid request")
        return request, message_log

    matching_request = send_request(request)
    update_status("Request Agent", "Request sent")

    while True:
        message_log.append(matching_request)
        update_status("Matching Agent", "Searching for a translator")
        offer = match_request(matching_request, translators)
        message_log.append(offer)

        if offer["performative"] != "REQUEST":
            update_status("Matching Agent", offer["content"])
            return {
                **request,
                "status": "Unassigned",
                "message": offer["content"],
            }, message_log

        translator_id = offer["translator_id"]
        translator = translators_by_id[translator_id]
        update_status("Matching Agent", f"Selected {translator_id}")
        update_status("Translator Agent", f"Waiting for {translator_id} to respond")

        reply = respond_to_request(
            offer, translator, accept=decisions[translator_id]
        )
        message_log.append(reply)
        update_status("Translator Agent", f'{translator_id}: {reply["performative"]}')

        if reply["performative"] == "REFUSE":
            excluded_ids.append(translator_id)
            matching_request = {
                "performative": "REQUEST",
                "sender": "Request Agent",
                "receiver": "Matching Agent",
                "content": request,
                "excluded_translator_ids": excluded_ids.copy(),
                "reason": reply["reason"],
            }
            continue

        update_status("Monitoring Agent", f"Monitoring {translator_id}")
        translator["status"] = "Busy"
        for update in service_updates[translator_id]:
            if update.get("completed", False):
                translator["status"] = "Available"
                update_status("Monitoring Agent", f"Service completed by {translator_id}")
                return {
                    **request,
                    "status": "Completed",
                    "translator_id": translator_id,
                }, message_log

            replacement_request = monitor_service(
                reply, max_wait_minutes=max_wait_minutes, **update
            )

            if replacement_request is not None:
                translator["status"] = "Unavailable"
                excluded_ids.append(translator_id)
                replacement_request["excluded_translator_ids"] = excluded_ids.copy()
                matching_request = replacement_request
                update_status(
                    "Monitoring Agent",
                    f"Requesting a replacement for {translator_id}",
                )
                break
        else:
            update_status("Monitoring Agent", f"Service in progress with {translator_id}")
            return {
                **request,
                "status": "In Progress",
                "translator_id": translator_id,
            }, message_log